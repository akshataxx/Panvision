"""PostgreSQL research accounts and doctor-owned case notes. No scan bytes stored."""
import argparse
import getpass
import hashlib
import hmac
import os
from pathlib import Path
import secrets
import uuid
import psycopg
from psycopg.rows import dict_row
import time
from contextlib import contextmanager


SESSION_IDLE_SECONDS = 20 * 60


class DatabaseConfigurationError(RuntimeError):
    pass


def database_url():
    url = os.environ.get('PANVISION_DATABASE_URL', '').strip()
    if not url:
        raise DatabaseConfigurationError('Set PANVISION_DATABASE_URL to your PostgreSQL connection URL before starting PanVision.')
    if not url.startswith(('postgresql://', 'postgres://')):
        raise DatabaseConfigurationError('PANVISION_DATABASE_URL must be a PostgreSQL connection URL.')
    return url


@contextmanager
def connect():
    with psycopg.connect(database_url(), row_factory=dict_row, connect_timeout=10) as db:
        yield db


def initialize():
    with connect() as db:
        db.execute('''
        CREATE TABLE IF NOT EXISTS doctors (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, email TEXT UNIQUE NOT NULL,
            name TEXT NOT NULL, salt BYTEA NOT NULL, password_hash BYTEA NOT NULL,
            active INTEGER NOT NULL DEFAULT 1, failures INTEGER NOT NULL DEFAULT 0,
            locked_until DOUBLE PRECISION NOT NULL DEFAULT 0, created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
        );
        ALTER TABLE doctors ADD COLUMN IF NOT EXISTS role TEXT NOT NULL DEFAULT 'doctor'
            CHECK (role IN ('doctor', 'admin'));
        CREATE TABLE IF NOT EXISTS doctor_sessions (
            token_hash TEXT PRIMARY KEY, doctor_id BIGINT NOT NULL REFERENCES doctors(id) ON DELETE CASCADE,
            expires_at DOUBLE PRECISION NOT NULL
        );
        ALTER TABLE doctor_sessions ADD COLUMN IF NOT EXISTS last_activity_at DOUBLE PRECISION NOT NULL DEFAULT 0;
        CREATE INDEX IF NOT EXISTS doctor_sessions_expiry ON doctor_sessions(expires_at);
        CREATE TABLE IF NOT EXISTS doctor_cases (
            doctor_id BIGINT NOT NULL REFERENCES doctors(id), study_id TEXT NOT NULL,
            notes TEXT NOT NULL DEFAULT '', updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
            PRIMARY KEY(doctor_id, study_id)
        );
        CREATE TABLE IF NOT EXISTS scan_uploads (
            id UUID PRIMARY KEY, doctor_id BIGINT NOT NULL REFERENCES doctors(id),
            filename VARCHAR(255) NOT NULL, sha256 TEXT, size_bytes BIGINT,
            shape_zyx INTEGER[], spacing_xyz DOUBLE PRECISION[],
            status TEXT NOT NULL CHECK (status IN ('validated','rejected')),
            notes TEXT NOT NULL DEFAULT '', created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
            updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
        );
        CREATE INDEX IF NOT EXISTS scan_uploads_owner_date ON scan_uploads(doctor_id,created_at DESC);
        CREATE TABLE IF NOT EXISTS scan_events (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            upload_id UUID NOT NULL REFERENCES scan_uploads(id),
            actor_id BIGINT NOT NULL REFERENCES doctors(id),
            event TEXT NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
        );
        CREATE INDEX IF NOT EXISTS scan_events_upload ON scan_events(upload_id,id);
        CREATE TABLE IF NOT EXISTS admin_audit (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            actor_id BIGINT REFERENCES doctors(id), target_id BIGINT REFERENCES doctors(id),
            action TEXT NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
        );
        ''')


def password_hash(password, salt):
    return hashlib.scrypt(password.encode(), salt=salt, n=16384, r=8, p=1, dklen=64)


def create_doctor(email, name, password, role='doctor'):
    if role not in ('doctor', 'admin'):
        raise ValueError('Invalid account role.')
    email, name = email.strip().lower(), name.strip()
    if '@' not in email or not name or len(password) < 12:
        raise ValueError('Use a valid email, a name, and a password of at least 12 characters.')
    salt = secrets.token_bytes(16)
    digest = password_hash(password, salt)
    initialize()
    with connect() as db:
        db.execute('INSERT INTO doctors(email,name,salt,password_hash,role) VALUES (%s,%s,%s,%s,%s)', (email, name, salt, digest, role))


def authenticate(email, password):
    with connect() as db:
        row = db.execute('SELECT * FROM doctors WHERE email=%s FOR UPDATE', (email.strip().lower(),)).fetchone()
        # Perform the expensive hash even for unknown accounts.
        digest = password_hash(password, row['salt'] if row else bytes(16))
        if not row or not row['active'] or row['locked_until'] > time.time():
            return None
        if not hmac.compare_digest(digest, row['password_hash']):
            failures = row['failures'] + 1
            db.execute('UPDATE doctors SET failures=%s,locked_until=%s WHERE id=%s',
                       (failures, time.time()+300 if failures >= 5 else 0, row['id']))
            return None
        db.execute('UPDATE doctors SET failures=0,locked_until=0 WHERE id=%s', (row['id'],))
        return {'id': row['id'], 'name': row['name'], 'email': row['email'], 'role': row['role']}


def saved_cases(doctor_id):
    with connect() as db:
        return {row['study_id']: row['notes'] for row in db.execute(
            'SELECT study_id,notes FROM doctor_cases WHERE doctor_id=%s', (doctor_id,))}


def save_case(doctor_id, study_id, notes):
    with connect() as db:
        db.execute('''INSERT INTO doctor_cases(doctor_id,study_id,notes) VALUES (%s,%s,%s)
                   ON CONFLICT(doctor_id,study_id) DO UPDATE SET notes=excluded.notes,updated_at=CURRENT_TIMESTAMP''',
                   (doctor_id, study_id, notes))


def migrate_sqlite(source):
    """Copy an existing SQLite database into an empty PostgreSQL database atomically."""
    import sqlite3
    path = Path(source).resolve()
    if not path.is_file():
        raise ValueError('SQLite source does not exist.')
    with sqlite3.connect(path.as_uri() + '?mode=ro', uri=True) as old:
        old.row_factory = sqlite3.Row
        doctors = old.execute('SELECT * FROM doctors').fetchall()
        cases = old.execute('SELECT * FROM doctor_cases').fetchall()
    initialize()
    with connect() as db:
        db.execute('LOCK TABLE doctors, doctor_cases IN ACCESS EXCLUSIVE MODE')
        if db.execute('SELECT COUNT(*) AS n FROM doctors').fetchone()['n']:
            raise ValueError('Migration requires an empty PostgreSQL doctors table.')
        for row in doctors:
            db.execute('INSERT INTO doctors(id,email,name,salt,password_hash,active,failures,locked_until,created_at) '
                       'VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s)', tuple(row[k] for k in
                       ('id','email','name','salt','password_hash','active','failures','locked_until','created_at')))
        for row in cases:
            db.execute('INSERT INTO doctor_cases(doctor_id,study_id,notes,updated_at) VALUES (%s,%s,%s,%s)',
                       tuple(row[k] for k in ('doctor_id','study_id','notes','updated_at')))
        db.execute("SELECT setval(pg_get_serial_sequence('doctors','id'), COALESCE((SELECT MAX(id) FROM doctors),1), "
                   "EXISTS(SELECT 1 FROM doctors))")
    return len(doctors), len(cases)



def new_session(doctor_id):
    token = secrets.token_urlsafe(32)
    digest = hashlib.sha256(token.encode()).hexdigest()
    now = time.time()
    expires = now + SESSION_IDLE_SECONDS
    with connect() as db:
        db.execute('DELETE FROM doctor_sessions WHERE expires_at <= %s', (time.time(),))
        db.execute('INSERT INTO doctor_sessions(token_hash,doctor_id,expires_at,last_activity_at) VALUES (%s,%s,%s,%s)',
                   (digest, doctor_id, expires, now))
    return token, expires


def session_doctor(token, touch=True):
    digest = hashlib.sha256(token.encode()).hexdigest()
    now = time.time()
    with connect() as db:
        if touch:
            # One statement validates and refreshes; an expired token cannot be revived.
            row = db.execute("""UPDATE doctor_sessions s SET last_activity_at=%s,expires_at=%s FROM doctors d
                                WHERE d.id=s.doctor_id AND s.token_hash=%s AND s.expires_at>%s
                                AND s.last_activity_at>%s AND d.active=1
                                RETURNING d.id,d.name,d.email,d.role""",
                             (now,now+SESSION_IDLE_SECONDS,digest,now,now-SESSION_IDLE_SECONDS)).fetchone()
        else:
            # Periodic UI status checks must not count as activity.
            row = db.execute("""SELECT d.id,d.name,d.email,d.role FROM doctor_sessions s JOIN doctors d ON d.id=s.doctor_id
                                WHERE s.token_hash=%s AND s.expires_at>%s AND s.last_activity_at>%s AND d.active=1""",
                             (digest,now,now-SESSION_IDLE_SECONDS)).fetchone()
        return dict(row) if row else None



def revoke_session(token):
    with connect() as db:
        db.execute('DELETE FROM doctor_sessions WHERE token_hash=%s', (hashlib.sha256(token.encode()).hexdigest(),))


class AccountConflict(ValueError):
    pass


def admin_lock(db, actor_id):
    # Serialize all web account mutations; recheck authority inside the transaction.
    db.execute('SELECT pg_advisory_xact_lock(724183)')
    actor = db.execute('SELECT role,active FROM doctors WHERE id=%s', (actor_id,)).fetchone()
    if not actor or actor['role'] != 'admin' or not actor['active']:
        raise PermissionError('Administrator access required.')


def list_accounts():
    with connect() as db:
        return [dict(row) for row in db.execute('SELECT id,name,email,role,active,created_at FROM doctors ORDER BY id')]


def admin_create_doctor(actor_id, email, name, password):
    salt = secrets.token_bytes(16)
    digest = password_hash(password, salt)
    with connect() as db:
        admin_lock(db, actor_id)
        row = db.execute("INSERT INTO doctors(email,name,salt,password_hash,role) VALUES (%s,%s,%s,%s,'doctor') "
                         'RETURNING id,name,email,role,active,created_at',
                         (email.strip().lower(), name.strip(), salt, digest)).fetchone()
        db.execute("INSERT INTO admin_audit(actor_id,target_id,action) VALUES (%s,%s,'doctor_created')", (actor_id,row['id']))
        return dict(row)


def admin_update_account(actor_id, target_id, active, role):
    with connect() as db:
        admin_lock(db, actor_id)
        target = db.execute('SELECT role,active FROM doctors WHERE id=%s FOR UPDATE', (target_id,)).fetchone()
        if target is None:
            raise LookupError('Account not found.')
        remaining = db.execute("SELECT COUNT(*) AS n FROM doctors WHERE role='admin' AND active=1 AND id<>%s", (target_id,)).fetchone()['n']
        if target['role'] == 'admin' and target['active'] and (not active or role != 'admin') and remaining == 0:
            raise AccountConflict('The last active administrator cannot be disabled or demoted.')
        row = db.execute('UPDATE doctors SET active=%s,role=%s WHERE id=%s RETURNING id,name,email,role,active,created_at',
                         (int(active), role, target_id)).fetchone()
        if not active or role != target['role']:
            db.execute('DELETE FROM doctor_sessions WHERE doctor_id=%s', (target_id,))
        db.execute('INSERT INTO admin_audit(actor_id,target_id,action) VALUES (%s,%s,%s)',
                   (actor_id,target_id, f"account_updated:role={role};active={bool(active)}"))
        return dict(row)


def admin_database_status():
    with connect() as db:
        counts = db.execute("SELECT (SELECT COUNT(*) FROM doctors) AS accounts, "
                            "(SELECT COUNT(*) FROM doctor_cases) AS saved_cases, "
                            "(SELECT COUNT(*) FROM doctor_sessions WHERE expires_at>%s AND last_activity_at>%s) AS active_sessions",
                            (time.time(),time.time()-SESSION_IDLE_SECONDS)).fetchone()
        audit = [dict(row) for row in db.execute('SELECT id,actor_id,target_id,action,created_at FROM admin_audit ORDER BY id DESC LIMIT 100')]
    return {'tables':['doctors','doctor_sessions','doctor_cases','admin_audit','scan_uploads','scan_events'], 'counts':dict(counts), 'audit':audit}


def change_password(doctor_id, current_password, new_password):
    if len(new_password) < 12 or len(new_password) > 1024 or current_password == new_password:
        raise ValueError('Choose a different password with 12 to 1024 characters.')
    with connect() as db:
        row = db.execute('SELECT * FROM doctors WHERE id=%s FOR UPDATE', (doctor_id,)).fetchone()
        if not row or not row['active'] or row['locked_until'] > time.time():
            return False
        current_hash = password_hash(current_password, row['salt'])
        if not hmac.compare_digest(current_hash, row['password_hash']):
            failures = row['failures'] + 1
            db.execute('UPDATE doctors SET failures=%s,locked_until=%s WHERE id=%s',
                       (failures, time.time()+300 if failures >= 5 else 0, doctor_id))
            return False
        salt = secrets.token_bytes(16)
        db.execute('UPDATE doctors SET salt=%s,password_hash=%s,failures=0,locked_until=0 WHERE id=%s',
                   (salt,password_hash(new_password,salt),doctor_id))
        db.execute('DELETE FROM doctor_sessions WHERE doctor_id=%s', (doctor_id,))
        db.execute("INSERT INTO admin_audit(actor_id,target_id,action) VALUES (%s,%s,'password_changed')", (doctor_id,doctor_id))
    return True


def record_upload(doctor_id, filename, status, sha256=None, size_bytes=None, shape=None, spacing=None):
    upload_id = uuid.uuid4()
    with connect() as db:
        db.execute('INSERT INTO scan_uploads(id,doctor_id,filename,status,sha256,size_bytes,shape_zyx,spacing_xyz) '
                   'VALUES (%s,%s,%s,%s,%s,%s,%s,%s)',
                   (upload_id,doctor_id,filename[:255],status,sha256,size_bytes,shape,spacing))
        db.execute('INSERT INTO scan_events(upload_id,actor_id,event) VALUES (%s,%s,%s)',
                   (upload_id,doctor_id,'upload_validated' if status=='validated' else 'upload_rejected'))
    return str(upload_id)


def upload_history(doctor_id=None, limit=50, offset=0):
    with connect() as db:
        rows = db.execute('SELECT u.id,u.doctor_id,d.name AS doctor_name,d.email AS doctor_email,u.filename,'
                          'u.size_bytes,u.shape_zyx,u.spacing_xyz,u.status,u.created_at,u.updated_at,'
                          "(SELECT COUNT(*) FROM scan_events e WHERE e.upload_id=u.id AND e.event='pdf_generated') AS reports "
                          'FROM scan_uploads u JOIN doctors d ON d.id=u.doctor_id '
                          'WHERE (%s::bigint IS NULL OR u.doctor_id=%s) ORDER BY u.created_at DESC,u.id LIMIT %s OFFSET %s',
                          (doctor_id,doctor_id,limit,offset)).fetchall()
        count = db.execute('SELECT COUNT(*) AS n FROM scan_uploads WHERE (%s::bigint IS NULL OR doctor_id=%s)',
                           (doctor_id,doctor_id)).fetchone()['n']
    return {'items':[dict(row) for row in rows], 'total':count}


def get_upload(upload_id, doctor_id=None):
    with connect() as db:
        row = db.execute('SELECT * FROM scan_uploads WHERE id=%s AND (%s::bigint IS NULL OR doctor_id=%s)',
                         (upload_id,doctor_id,doctor_id)).fetchone()
        if row is None:
            raise LookupError('Upload not found.')
        events = [dict(event) for event in db.execute('SELECT event,actor_id,created_at FROM scan_events WHERE upload_id=%s ORDER BY id', (upload_id,))]
    result = dict(row)
    result['events'] = events
    return result


def save_upload_notes(upload_id, doctor_id, notes):
    with connect() as db:
        row = db.execute('UPDATE scan_uploads SET notes=%s,updated_at=CURRENT_TIMESTAMP '
                         'WHERE id=%s AND doctor_id=%s RETURNING id', (notes,upload_id,doctor_id)).fetchone()
        if row is None:
            raise LookupError('Upload not found.')
        db.execute("INSERT INTO scan_events(upload_id,actor_id,event) VALUES (%s,%s,'notes_saved')", (upload_id,doctor_id))


def record_report(upload_id, doctor_id, sha256, notes):
    with connect() as db:
        row = db.execute("UPDATE scan_uploads SET notes=%s,updated_at=CURRENT_TIMESTAMP "
                         "WHERE id=%s AND doctor_id=%s AND sha256=%s AND status='validated' RETURNING id",
                         (notes,upload_id,doctor_id,sha256)).fetchone()
        if row is None:
            raise LookupError('Upload not found or file does not match.')
        db.execute("INSERT INTO scan_events(upload_id,actor_id,event) VALUES (%s,%s,'pdf_generated')", (upload_id,doctor_id))


def connection_error_message(exc):
    """Classify locally without returning raw errors that may contain credentials."""
    state = getattr(exc, 'sqlstate', None)
    message = str(exc).lower()
    if state == '28P01' or 'password authentication failed' in message:
        return 'Authentication failed: check the Admin1 password and rebuild PANVISION_DATABASE_URL.'
    if state == '3D000' or ('database' in message and 'does not exist' in message):
        return 'Database missing: create panvision under the server Databases page.'
    if state == '42501' or 'permission denied' in message:
        return 'Permission denied: the database user needs access to the database and permission to create tables in the public schema.'
    if 'no pg_hba.conf entry' in message or 'not allowed to access' in message:
        return 'Connection rejected: check the Azure Networking firewall rule for your current public IP and the required TLS settings.'
    if any(word in message for word in ('certificate', 'ssl', 'tls')):
        return 'TLS connection failed: check the Azure server TLS settings and client certificate configuration.'
    if any(word in message for word in ('could not translate host', 'name or service not known', 'nodename nor servname', 'failed to resolve')):
        return 'Hostname lookup failed: check the server hostname, internet connection and DNS.'
    if 'timeout' in message or 'timed out' in message:
        return 'Connection timed out: check server status Ready, public networking, your current IP firewall rule, and whether your network blocks port 5432.'
    if 'refused' in message:
        return 'Connection refused: check server status, hostname, port 5432 and network access.'
    return 'PostgreSQL connection failed. Check server status, PostgreSQL password authentication, networking and connection settings.'


def check_connection():
    with connect() as db:
        db.execute('SELECT 1')
        privileges = db.execute("SELECT has_schema_privilege(current_user, 'public', 'CREATE') AS can_create").fetchone()
    print('Connected to PostgreSQL successfully. Password and database are valid.')
    print('Can create tables in public schema: ' + ('yes' if privileges['can_create'] else 'no'))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description='Manage PanVision PostgreSQL accounts')
    parser.add_argument('command', choices=['check', 'init', 'create-doctor', 'create-admin', 'migrate-sqlite'])
    parser.add_argument('--source', help='Existing SQLite database to copy (never modified)')
    args = parser.parse_args()
    try:
        if args.command == 'check':
            check_connection()
        elif args.command == 'init':
            initialize()
            print('PostgreSQL schema initialized.')
        elif args.command == 'migrate-sqlite':
            if not args.source:
                raise ValueError('--source is required.')
            doctors, cases = migrate_sqlite(args.source)
            print(f'Migrated {doctors} doctors and {cases} saved cases.')
        else:
            email = input('Account email: ')
            name = input('Display name: ')
            password = getpass.getpass('Password (12+ characters): ')
            if password != getpass.getpass('Confirm password: '):
                raise ValueError('Passwords do not match.')
            role = 'admin' if args.command == 'create-admin' else 'doctor'
            create_doctor(email, name, password, role=role)
            print(f'{role.title()} account created.')
    except psycopg.errors.UniqueViolation:
        raise SystemExit('An account with that email already exists.')
    except psycopg.Error as exc:
        raise SystemExit(connection_error_message(exc))
    except (ValueError, DatabaseConfigurationError) as exc:
        raise SystemExit(str(exc))
